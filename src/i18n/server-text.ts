const FR_PATTERNS: [RegExp, string][] = [
  [/^(.+) is connected\. Kaya pulled a first snapshot of your data\.$/, "$1 est connecté. Kaya a récupéré un premier aperçu de vos données."],
];

export function translateServerText(text: string, locale: Locale): string;
export function translateServerText(text: string | null | undefined, locale: Locale): string | null | undefined;
export function translateServerText(text: string | null | undefined, locale: Locale): string | null | undefined {
  if (!text || locale === "en") return text;
  const exact = FR[text];
  if (exact) return exact;
  for (const [pattern, replacement] of FR_PATTERNS) if (pattern.test(text)) return text.replace(pattern, replacement);
  return text;
}
