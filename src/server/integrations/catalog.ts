export type ReadCapability = (typeof READ_CAPABILITIES)[number];
export type WriteCapability = (typeof WRITE_CAPABILITIES)[number];
export type Capability = ReadCapability | WriteCapability;

export type IntegrationDomain = "revenue" | "analytics" | "search" | "ads" | "social" | "email" | "crm" | "product" | "creators";

export interface IntegrationDefinition {
  provider: string;
  name: string;
  domain: IntegrationDomain;
  priority: "P0" | "P1" | "P2";
  stage: string;
  mustHave: boolean;
  authType: "oauth" | "api_key";
  risk: "read_only" | "publish" | "spend" | "sensitive";
  reads: ReadCapability[];
  writes: WriteCapability[];
  /** What the agent can do better once connected. Shown in onboarding. */
  unlocks: string;
  permissions: { label: string; access: "read" | "write" }[];
  apiNotes: string;
}

