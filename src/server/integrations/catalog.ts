export function getIntegration(provider: string): IntegrationDefinition | undefined {
  return INTEGRATIONS.find((i) => i.provider === provider);
}

export function providersFor(capability: Capability): IntegrationDefinition[] {
  return INTEGRATIONS.filter((i) => (i.reads as Capability[]).includes(capability) || (i.writes as Capability[]).includes(capability));
}
